/* No npm dependency. Compile with the explicitly selected MinGW toolchain. */
const fs = require("fs");
const cp = require("child_process");
const crypto = require("crypto");
const path = require("path");
process.chdir(path.resolve(__dirname, ".."));
const cc = process.env.FPS_BRIDGE_CC || "x86_64-w64-mingw32-gcc";
const args = [
  "-std=c11",
  "-O2",
  "-Wall",
  "-Wextra",
  "-Werror",
  "-municode",
  "-static",
  "-s",
  "-Wl,--no-insert-timestamp",
  "native/fps-bridge/bridge.c",
  "-lpsapi",
  "-ladvapi32",
  "-o",
  ".tmp/fps-bridge.exe",
];
fs.mkdirSync(".tmp", { recursive: true });
cp.execFileSync(cc, args, { stdio: "inherit" });
const bytes = fs.readFileSync(".tmp/fps-bridge.exe");
const sha256 = crypto.createHash("sha256").update(bytes).digest("hex");
const manifest = {
  version: 1,
  filename: "fps-bridge.exe",
  size: bytes.length,
  sha256,
};
const modulePath = "src/clients/mhy/hk4e/fps-bridge-manifest.ts";
if (process.argv.includes("--record")) {
  fs.writeFileSync(
    modulePath,
    "// Generated by scripts/build-fps-bridge.cjs --record. See native/fps-bridge/README.md.\nexport const FPS_BRIDGE_MANIFEST = Object.freeze(" +
      JSON.stringify(manifest, null, 2)
        .replace(/"([A-Za-z0-9_]+)":/g, "$1:")
        .replace(/\n}/, ",\n}") +
      ");\n"
  );
  fs.writeFileSync(
    "native/fps-bridge/build-record.json",
    JSON.stringify(
      {
        ...manifest,
        compiler: cp
          .execFileSync(cc, ["--version"], { encoding: "utf8" })
          .split("\n")[0],
        command: [cc, ...args],
        sourceSha256: crypto
          .createHash("sha256")
          .update(fs.readFileSync("native/fps-bridge/bridge.c"))
          .digest("hex"),
        registrySourceSha256: crypto
          .createHash("sha256")
          .update(fs.readFileSync("native/fps-bridge/registry.c"))
          .digest("hex"),
        upstreamRepository: "rishabhroyy/genshin-fps-unlock-universal",
        upstreamSource: "Fork/unlockfps/FpsPatterns.cs",
        upstreamRevision: "56b9c64381ef9fd59e916dc9bf547d3210ab5db1",
      },
      null,
      2
    ) + "\n"
  );
} else {
  const expected = fs.readFileSync(modulePath, "utf8");
  if (!expected.includes(sha256))
    throw Error(
      "Bridge build differs from recorded artifact. Review toolchain/source; use --record only for an intentional source change."
    );
}
fs.mkdirSync("sidecar/fps-bridge", { recursive: true });
fs.copyFileSync(".tmp/fps-bridge.exe", "sidecar/fps-bridge/fps-bridge.exe");
fs.copyFileSync(
  "native/fps-bridge/LICENSE.upstream",
  "sidecar/fps-bridge/LICENSE.upstream"
);
console.log(JSON.stringify(manifest));
